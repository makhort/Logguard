/// (latitude, longitude) of the capital, for an ISO country code.
pub fn capital(code: &str) -> Option<(f64, f64)> {
    CAPITALS.binary_search_by(|(c, _, _)| (*c).cmp(code)).ok().map(|i| (CAPITALS[i].1, CAPITALS[i].2))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sorted_unique_and_on_the_globe() {
        assert!(CAPITALS.windows(2).all(|w| w[0].0 < w[1].0), "sorted for binary search, no duplicates");
        assert!(CAPITALS.iter().all(|(_, lat, lon)| lat.abs() <= 90.0 && lon.abs() <= 180.0));
        assert_eq!(capital("UA"), Some((50.45, 30.52)));
        assert_eq!(capital("ZZ"), None);
    }
}
